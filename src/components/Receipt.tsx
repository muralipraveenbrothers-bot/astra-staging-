/** Discharge summary print sheet. */
export function DischargeSummaryView({
  patientId,
  diagnosis,
  treatment,
  procedures,
  medications,
  followUpDate,
  admitDate,
  dischargeDate,
}: {
  patientId: string;
  diagnosis: string;
  treatment: string;
  procedures: string;
  medications: string;
  followUpDate: string;
  admitDate: string;
  dischargeDate: string;
}) {
  const Row = ({ k, v }: { k: string; v: string }) => (
    <div className="row"><span>{k}</span><span style={{ maxWidth: 190, textAlign: "right" }}>{v || "—"}</span></div>
  );
  return (
    <div className="print-zone">
      <div className="receipt" style={{ width: 420 }}>
        <h4>PM Brothers Multispeciality Hospital</h4>
        <div className="sub">DISCHARGE SUMMARY</div>
        <div style={{ textAlign: "center", fontWeight: 700, fontSize: 13, border: "1px dashed #000", padding: "4px 6px", margin: "6px 0" }}>
          DISCHARGED: {dischargeDate}
        </div>
        <div className="dash" />
        <Row k="Patient ID" v={patientId} />
        <Row k="Admission date" v={admitDate} />
        <Row k="Discharge date" v={dischargeDate} />
        <div className="dash" />
        <Row k="Diagnosis" v={diagnosis} />
        <Row k="Treatment given" v={treatment} />
        <Row k="Procedures" v={procedures} />
        <Row k="Meds on discharge" v={medications} />
        <div className="dash" />
        <Row k="Follow-up" v={followUpDate} />
        <Row k="Outcome check" v="Day-5 reminder auto-scheduled" />
        <div className="dash" />
        <div className="foot">
          This summary was compiled by Astra AI from the patient record and verified by the treating physician.
        </div>
      </div>
    </div>
  );
}
